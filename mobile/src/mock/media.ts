// a poster for a reel topic. every seeded topic resolves to some distinct-enough image.
export function reelPoster(topic: string, variant = 0): ImageSource {
  const k = ALIAS[topic] ?? topic.replace(/\s+/g, "");
  if (k === "thrifting" && variant % 2 === 1) return REEL.thrifting2;
  if (REEL[k]) return REEL[k];
  let h = 0;
  for (const c of topic) h = (h * 31 + c.charCodeAt(0)) >>> 0;
  return REEL[REEL_KEYS[h % REEL_KEYS.length]];
}
