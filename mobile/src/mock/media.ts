// "Inés Castillo" -> "ines". seeded users are keyed by first name.
function key(name: string): string {
  return (name.split(" ")[0] ?? name).normalize("NFD").replace(/[\u0300-\u036f]/g, "").toLowerCase();
}

export function avatarFor(name: string): ImageSource | null {
  return AVATARS[key(name)] ?? null;
}

